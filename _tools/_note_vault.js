'结算时把「抵达竖井口」这类**瞬时目标**又重判了一次 —— 人都走到撤离点了，当然不在井口旁，于是判未达成、下一章不解锁。现在以**局内锁定的完成状态**为准（护送类仍按撤离那一刻判）。',
